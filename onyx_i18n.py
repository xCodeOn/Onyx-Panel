_SORTED_KEYS = sorted(PAIRS, key=len, reverse=True)
_COMBINED = None
# Cyrillic runs in the rendered markup: they end at ASCII letters, quotes,
# tags and code, so dictionary keys match text nodes exactly.  The cheap
# single-class scan makes the pass linear; heavy phrase matching happens
# only inside the short runs that miss the exact lookup.
_RUN = re.compile(r'[а-яёА-ЯЁ][а-яёА-ЯЁ0-9 \t.,;:!?%…«»()\-—–№+/=*]*')


def _engine():
    global _COMBINED
    if _COMBINED is None:
        parts = [r'(?<!\w)' + re.escape(key) + r'(?!\w)' for key in _SORTED_KEYS]
        _COMBINED = re.compile('|'.join(parts))
    return _COMBINED


def _translate_run(match):
    run = match.group(0)
    hit = PAIRS.get(run)
    if hit is not None:
        return hit
    stripped = run.strip()
    hit = PAIRS.get(stripped)
    if hit is None:
        return _engine().sub(lambda m: PAIRS[m.group(0)], run)
    lead = run[:len(run) - len(run.lstrip())]
    trail = run[len(run.rstrip()):]
    return lead + hit + trail


def _plain(text):
    if not _CYR.search(text):
        return text
    for pattern, repl in EXTRA_RULES:
        text = pattern.sub(repl, text)
    return _RUN.sub(_translate_run, text)


def t(text):
    """Translate a server-side string (JSON messages) for English viewers."""
    if lang() != 'en' or not isinstance(text, str) or not _CYR.search(text):
        return text
    return _plain(text)


def walk(value):
    """Deep-translate a JSON-serialisable payload for English viewers."""
    if lang() != 'en':
        return value
    if isinstance(value, str):
        return _plain(value) if _CYR.search(value) else value
    if isinstance(value, dict):
        return {k: walk(v) for k, v in value.items()}
    if isinstance(value, list):
        return [walk(v) for v in value]
    return value


def document(html):
    """Translate a fully rendered HTML document for English viewers."""
    if lang() != 'en' or not _CYR.search(html):
        return html
    html = _LANG_ATTR.sub('<html lang="en"', html)
    return _plain(html)
