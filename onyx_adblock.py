"""DNS-level adblock for the panel: an unbound local-zone blocklist.

The list (OISD small) is downloaded daily, converted into
`local-zone: "domain" always_nxdomain` entries and dropped into
/etc/unbound/unbound.conf.d/. Xray resolves through unbound while the DoT
marker exists, and AWG clients get the tunnel gateway as their DNS, so every
protocol the panel serves is filtered by the same list.

Honest scope note: same-domain ads (YouTube, Instagram, TikTok feeds) can not
be filtered by any DNS or VPN server — that needs client-side blockers. The
settings card says so out loud.
"""
import ipaddress
import os
import re
import subprocess
import time

LIST_URL = "https://small.oisd.nl/"
LIST_CACHE = "/var/lib/onyx-panel/adblock-list.txt"
CONF_PATH = "/etc/unbound/unbound.conf.d/onyx-adblock.conf"
ENABLED_MARKER = "/etc/onyx-panel/adblock.enabled"

_DOMAIN_RE = re.compile(r"^(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$")
_MAX_DOMAINS = 400000
MAX_CUSTOM = 1000


def normalize(state):
    """Validated data.json["adblock"] section."""
    state = state if isinstance(state, dict) else {}
    allow = [str(x).strip().strip(".").lower() for x in (state.get("allow") or []) if str(x).strip()]
    deny = [str(x).strip().strip(".").lower() for x in (state.get("deny") or []) if str(x).strip()]
    return {
        "enabled": bool(state.get("enabled", False)),
        "updated_ts": int(state.get("updated_ts", 0) or 0),
        "domains": int(state.get("domains", 0) or 0),
        "error": str(state.get("error", "") or "")[:200],
        "allow": sorted({x for x in allow if _DOMAIN_RE.match(x)})[:MAX_CUSTOM],
        "deny": sorted({x for x in deny if _DOMAIN_RE.match(x)})[:MAX_CUSTOM],
    }


def enabled():
    return os.path.exists(ENABLED_MARKER)


def parse_list(text):
    """Adblock-style wildcard list (`||domain.tld^`) -> (deny, allow) domain sets.

    Comments (!, #), path rules and cosmetic filters are skipped; explicit
    exception rules (@@||…) feed the allow set.
    """
    deny = set()
    allow = set()
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line[0] in "!#":
            continue
        if line.startswith("@@"):
            candidate, target = line[2:], allow
        else:
            candidate, target = line, deny
        if not candidate.startswith("||"):
            continue  # hosts-file lines and element rules are out of scope
        candidate = candidate[2:].split("^", 1)[0].split("$", 1)[0]
        if "/" in candidate:
            continue  # path rules are page-specific, never whole-domain
        candidate = candidate.strip(".").lower()
        if "*" in candidate or not _DOMAIN_RE.match(candidate):
            continue
        target.add(candidate)
        if len(target) > _MAX_DOMAINS:
            raise ValueError("Слишком большой блоклист.")
    return deny, allow


def parse_custom(text):
    """Custom allow/deny textarea content: one domain per line, commas ok."""
    items = re.split(r"[\s,]+", str(text or ""))
    return [x for x in items if x]


def gateway_ips(users):
    """Tunnel gateway IPs of enabled AWG profiles — the DNS address their
    client configs point at while adblock is on."""
    out = set()
    for user in users or []:
        if user.get("protocol") not in ("awg20", "awg31") or not user.get("enabled", True):
            continue
        raw = str(user.get("server_address", "")).split("/")[0]
        try:
            out.add(str(ipaddress.ip_address(raw)))
        except ValueError:
            continue
    return sorted(out)


def render_conf(deny, allow, gateways=()):
    """Full unbound fragment: AWG interfaces/access-control + local-zones."""
    lines = ["# Onyx Panel adblock — regenerated by the panel, do not edit.",
             "server:",
             # AWG tunnels come up after unbound at boot; without freebind the
             # gateway addresses do not exist yet and unbound refuses to start.
             "    ip-freebind: yes"]
    for ip in gateways:
        lines.append("    interface: %s" % ip)
        # AWG links are /30: the client is the only other host on the link.
        lines.append("    access-control: %s/30 allow" % ip)
    for domain in sorted(set(allow)):
        lines.append('    local-zone: "%s" transparent' % domain)
    for domain in sorted(set(deny) - set(allow)):
        lines.append('    local-zone: "%s" always_nxdomain' % domain)
    return "\n".join(lines) + "\n"


def fetch_list(url=LIST_URL):
    """Download the blocklist text via curl (present on every server)."""
    result = subprocess.run(["curl", "-fsSL", "--retry", "3", "--retry-all-errors",
                             "--connect-timeout", "20", "--max-time", "300", url],
                            capture_output=True, timeout=330)
    if result.returncode:
        raise RuntimeError("Не удалось скачать блоклист (код curl %d)." % result.returncode)
    text = result.stdout.decode("utf-8", "replace")
    if len(text) < 100000:
        raise RuntimeError("Блоклист подозрительно короткий — отказ.")
    return text


def _reload_unbound():
    check = subprocess.run(["unbound-checkconf", CONF_PATH], capture_output=True, timeout=60)
    if check.returncode:
        raise RuntimeError("unbound-checkconf отклонил конфиг: "
                           + (check.stderr or check.stdout).decode("utf-8", "replace")[-200:])
    subprocess.run(["systemctl", "reload", "unbound"], capture_output=True, timeout=60)
    if subprocess.run(["systemctl", "is-active", "--quiet", "unbound"],
                      capture_output=True, timeout=10).returncode:
        # reload could not bring it up (e.g. a stale socket) — try one restart
        # and fail loudly if the resolver still is not serving: with the DoT
        # marker on, Xray has no DNS without unbound.
        subprocess.run(["systemctl", "restart", "unbound"], capture_output=True, timeout=60)
        if subprocess.run(["systemctl", "is-active", "--quiet", "unbound"],
                          capture_output=True, timeout=10).returncode:
            raise RuntimeError("unbound не поднялся после применения конфига.")


def probe_unbound():
    """Fail-closed liveness check used by the panel routes after touching unbound."""
    if subprocess.run(["systemctl", "is-active", "--quiet", "unbound"],
                      capture_output=True, timeout=10).returncode:
        raise RuntimeError("unbound не запущен после перезапуска.")


def apply(state, users=None):
    """Write the zones conf from the cached list and reload unbound;
    returns the blocked count. The cache must exist (refresh() fills it)."""
    state = normalize(state)
    if not os.path.isfile(LIST_CACHE):
        raise RuntimeError("Блоклист ещё не скачан — выполните обновление.")
    with open(LIST_CACHE, encoding="utf-8") as handle:
        deny, listed_allow = parse_list(handle.read())
    deny |= set(state["deny"])
    allow = set(state["allow"]) | listed_allow
    text = render_conf(deny, allow, gateway_ips(users))
    os.makedirs(os.path.dirname(CONF_PATH), exist_ok=True)
    tmp = CONF_PATH + ".tmp"
    with open(tmp, "w", encoding="utf-8") as handle:
        handle.write(text)
    os.replace(tmp, CONF_PATH)
    try:
        _reload_unbound()
    except Exception:
        # A conf that failed validation must not wait on disk for the next
        # unbound restart — the running resolver keeps its previous zones.
        try: os.unlink(CONF_PATH)
        except OSError: pass
        raise
    return len(deny - allow)


def remove():
    """Drop the zones conf and reload unbound (the service itself stays)."""
    try:
        os.unlink(CONF_PATH)
    except FileNotFoundError:
        pass
    subprocess.run(["systemctl", "reload", "unbound"], capture_output=True, timeout=60)


def refresh(state, users=None):
    """Fetch the current list, cache it and apply; returns (state, changed)."""
    state = normalize(state)
    text = fetch_list()
    with open(LIST_CACHE, "w", encoding="utf-8") as handle:
        handle.write(text)
    count = apply(state, users)
    state.update(updated_ts=int(time.time()), domains=count, error="")
    return state
